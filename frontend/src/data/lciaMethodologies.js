// Dictionary lookup for instant retrieval by key or alias
export const METHODOLOGIES = {};

ALL_METHODOLOGIES.forEach(m => {
  METHODOLOGIES[m.id] = m;
  METHODOLOGIES[m.name] = m;
  if (m.alias) {
    METHODOLOGIES[m.alias] = m;
  }
});

// Helper to look up methodology by any ID, alias, or exact name
export function getMethodology(keyOrName) {
  if (!keyOrName) return METHODOLOGIES.traci21 || ALL_METHODOLOGIES[0];
  if (METHODOLOGIES[keyOrName]) return METHODOLOGIES[keyOrName];
  const found = ALL_METHODOLOGIES.find(
    m => m.id.toLowerCase() === String(keyOrName).toLowerCase() ||
         m.name.toLowerCase() === String(keyOrName).toLowerCase() ||
         (m.alias && m.alias.toLowerCase() === String(keyOrName).toLowerCase())
  );
  return found || METHODOLOGIES.traci21 || ALL_METHODOLOGIES[0];
}
